package Operators;

public class Assignment {
    public static void main(String[] args){
    int a = 50;
    System.out.println("Initial = " + a);
    a+=10;
    System.out.println("After += 10 = " + a);
    a-=5;
    System.out.println("After -= 5 = " + a);
    a*=2;
    System.out.println("After *= 2 = " + a);
    a/=5;
    System.out.println("After /= 5 = " + a);
    a%=7;
    System.out.println("After %= 7 = " + a);

    }  
}
